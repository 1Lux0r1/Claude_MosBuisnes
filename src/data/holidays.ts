/* ---------------------------------------------------------------------------
   Производственный календарь РФ — справочник дат (п.1 ТЗ).

   Ключ — дата в формате YYYY-MM-DD (совпадает с dayKey() из src/data.ts).
   Тип дня определяется ТОЛЬКО по этому справочнику, в коде не вычисляется.

   holiday      — нерабочий праздничный день    → красное число, красная рамка
   transferred  — выходной из-за переноса        → чёрное число, красная рамка
                  (в связи с праздником)
   weekend      — обычный выходной (сб/вс) внутри → чёрное число, красная рамка
                  непрерывного блока нерабочих
                  дней вокруг праздника

   Красное число — только у самих праздничных дат. У переносов и выходных
   внутри блока число чёрное, но рамка тоже красная — чтобы весь непрерывный
   блок нерабочих дней читался единым выделением.

   Обычные выходные ВНЕ праздничных блоков и рабочие дни здесь НЕ
   перечисляются — они отображаются как сейчас в макете.

   Год: 2026. Это макет — тип любого дня правится здесь, в одном месте.

   ⚠️ Фиксированные праздничные даты (1–8 января, 23 февраля, 8 марта, 1 и
   9 мая, 12 июня, 4 ноября) — достоверны. Конкретные даты переносов
   (transferred) следует сверить с официальным постановлением Правительства
   РФ о переносе выходных дней в 2026 году и при необходимости поправить
   прямо здесь.
--------------------------------------------------------------------------- */

